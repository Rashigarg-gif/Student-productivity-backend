// This searches for the .env file and loads MONGO_URI into the server's memory so that server can access dbms password.
require('dotenv').config();

const mongoose = require('mongoose');

const dns = require('dns');
dns.setServers(['8.8.8.8', '8.8.4.4']);

//import the Express library
const express = require('express');

//executes the main Express function which is a standard js fn, which instantiates internally and returns a brand new server object.
//express is a factory function.
const app = express();

//PORT tells which program should recieve the incoming request.
const PORT = 3000;

//PARSES DATA RECIEVED FROM REACT NATIVE TO JSON OBJECT FORMAT FOR CODE TO READ EASILY. This runs on every single request.
app.use(express.json());

const Task= require('./models/Task');
const Class = require('./models/Class');

// this tells mongoose to take the string and try to log in to mongoDB account database
mongoose.connect(process.env.MONGO_URI)
  //if login is successful .then line executes otherwise .catch line
  .then(() => console.log('Connected to MongoDB!'))
  .catch((err) => console.error('Could not connect to MongoDB...', err));

// TASKS REQUESTS
// A POST route to receive new tasks
app.post('/tasks', async (req, res) => {
  try {
    const task = new Task(req.body);
    //.save() method commands Mongoose to translate the local object into a MongoDB insertion query and send it to your Atlas database.
    //savedtask contains the final doc now with autogenerated id and timestamps.
    const savedTask = await task.save();
    res.status(201).json(savedTask); // 201 means "Created successfully"
  } catch (error) {
    res.status(400).json({ message: error.message });
  }
});

// A GET route to fetch all tasks
app.get('/tasks', async (req, res) => {
  try {
    const tasks = await Task.find(); // Fetches all documents from the 'tasks' collection
    res.status(200).json(tasks); 
  } catch (error) {
    res.status(500).json({ message: error.message }); // 500 means "Internal Server Error"
  }
});

// Update a task 
//: in url tells that id is variable.
app.put('/tasks/:id', async (req, res) => {
  try {
    const { id } = req.params; // Extracts the ID variable from the URL string
    const updatedTask = await Task.findByIdAndUpdate(id, req.body, { new: true }); 
    // { new: true } commands Mongoose to return the newly updated record instead of the old one
    if (!updatedTask) return res.status(404).json({ message: 'Task not found' });
    res.status(200).json(updatedTask);
  } catch (error) {
    res.status(400).json({ message: error.message });
  }
});

// Delete a task
app.delete('/tasks/:id', async (req, res) => {
  try {
    const { id } = req.params;
    const deletedTask = await Task.findByIdAndDelete(id);
    
    if (!deletedTask) return res.status(404).json({ message: 'Task not found' });
    res.status(200).json({ message: 'Task deleted successfully' });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
});



// CLASS REQUESTS
app.post('/classes', async (req, res) => {
  try {
    const newClass = new Class(req.body);
    const savedClass = await newClass.save();
    res.status(201).json(savedClass);
  } catch (error) {
    res.status(400).json({ message: error.message });
  }
});

app.get('/classes', async (req, res) => {
  try {
    const classes = await Class.find();
    res.status(200).json(classes);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
});

app.delete('/classes/:id', async (req, res) => {
  try {
    const { id } = req.params;
    const deletedClass = await Class.findByIdAndDelete(id);
    
    if (!deletedClass) return res.status(404).json({ message: 'Class not found' });
    res.status(200).json({ message: 'Class deleted successfully' });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
});

//commands Node.js to lock onto Port 3000 and create a continuous, running process that stays awake indefinitely to listen for connections.
// Without this line, Node.js would read your file top-to-bottom and immediately exit
app.listen(PORT, () => {
  console.log(`Server is running on port ${PORT}`);
}); 